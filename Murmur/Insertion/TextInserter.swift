import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Inserts text into whatever app the user was typing in.
///
/// Murmur pastes: it puts the text on the clipboard, sends ⌘V to the target app, then puts
/// the previous clipboard contents back. Writing through the Accessibility API
/// (`AXUIElementSetAttributeValue(kAXSelectedTextAttribute)`) looks cleaner, but it is
/// silently ignored by exactly the apps Murmur matters most in: terminals (Terminal, iTerm,
/// so also Claude Code), Electron editors (VS Code, Cursor, Slack) and web text fields, where
/// it may even report success without inserting anything or bypass the page's input events.
/// A paste is handled by every one of them like a user's own paste: undo works, terminals use
/// bracketed paste so multi-line text isn't executed line by line, and editors keep formatting.
@MainActor
enum TextInserter {
    enum Outcome: Equatable {
        case pasted
        /// Text was left on the clipboard instead. The associated value explains why.
        case copied(CopyReason)
    }

    enum CopyReason: Equatable {
        case accessibilityNotGranted
        case targetUnavailable(appName: String)
    }

    static func insert(_ text: String, into target: NSRunningApplication?, restoreClipboard: Bool) async -> Outcome {
        guard AXIsProcessTrusted() else {
            Clipboard.write(text, transient: false)
            return .copied(.accessibilityNotGranted)
        }

        if let target, !(await bringToFront(target)) {
            Clipboard.write(text, transient: false)
            return .copied(.targetUnavailable(appName: target.localizedName ?? "the app"))
        }

        // Physical modifiers still held (e.g. from a push-to-talk shortcut) would turn ⌘V into ⌘⇧V.
        await waitForModifierKeysUp()

        let snapshot = restoreClipboard ? Clipboard.snapshot() : nil
        let changeCount = Clipboard.write(text, transient: restoreClipboard)
        postCommandV()

        if let snapshot {
            // Give the target app time to read the clipboard before restoring it. Skip the restore
            // if anything else wrote to the clipboard in the meantime.
            try? await Task.sleep(for: .milliseconds(450))
            if NSPasteboard.general.changeCount == changeCount {
                Clipboard.restore(snapshot)
            }
        }
        Log.insertion.info("Pasted \(text.count) characters into \(target?.bundleIdentifier ?? "frontmost app", privacy: .public)")
        return .pasted
    }

    /// Re-activates the app that was frontmost when dictation started, in case the user
    /// switched away while Murmur was processing.
    private static func bringToFront(_ app: NSRunningApplication) async -> Bool {
        if app.isTerminated { return false }
        if NSWorkspace.shared.frontmostApplication?.processIdentifier == app.processIdentifier { return true }
        app.activate(options: [])
        for _ in 0..<40 {
            try? await Task.sleep(for: .milliseconds(20))
            if NSWorkspace.shared.frontmostApplication?.processIdentifier == app.processIdentifier {
                // Let the app restore its key window and first responder.
                try? await Task.sleep(for: .milliseconds(80))
                return true
            }
        }
        return false
    }

    private static func waitForModifierKeysUp() async {
        let modifiers: CGEventFlags = [.maskCommand, .maskAlternate, .maskControl, .maskShift]
        for _ in 0..<50 {
            if CGEventSource.flagsState(.hidSystemState).intersection(modifiers).isEmpty { return }
            try? await Task.sleep(for: .milliseconds(20))
        }
    }

    private static func postCommandV() {
        let source = CGEventSource(stateID: .hidSystemState)
        let vKey = KeyboardLayout.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        let commandKey = CGKeyCode(kVK_Command)

        let events: [(CGKeyCode, Bool, CGEventFlags)] = [
            (commandKey, true, .maskCommand),
            (vKey, true, .maskCommand),
            (vKey, false, .maskCommand),
            (commandKey, false, []),
        ]
        for (key, isDown, flags) in events {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: isDown) else { continue }
            event.flags = flags
            event.post(tap: .cghidEventTap)
        }
    }
}

/// Clipboard helpers. Text Murmur places only temporarily is marked with the
/// nspasteboard.org "transient" types so clipboard managers don't record it.
@MainActor
enum Clipboard {
    struct Snapshot {
        let items: [[NSPasteboard.PasteboardType: Data]]
    }

    private static let transientTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    @discardableResult
    static func write(_ text: String, transient: Bool) -> Int {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        if transient {
            for type in transientTypes { pasteboard.setData(Data(), forType: type) }
        }
        return pasteboard.changeCount
    }

    static func snapshot() -> Snapshot {
        let items = NSPasteboard.general.pasteboardItems?.map { item -> [NSPasteboard.PasteboardType: Data] in
            var contents: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { contents[type] = data }
            }
            return contents
        } ?? []
        return Snapshot(items: items)
    }

    static func restore(_ snapshot: Snapshot) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let items = snapshot.items.filter { !$0.isEmpty }.map { contents in
            let item = NSPasteboardItem()
            for (type, data) in contents { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }
}
